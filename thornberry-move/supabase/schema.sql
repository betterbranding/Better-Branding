-- Thornberry Move: tables + row-level security.
-- Only the emails in move_allowed_users can read or write anything.

create table if not exists public.move_allowed_users (
  email text primary key
);

create table if not exists public.move_settings (
  key text primary key,
  value text not null
);

create table if not exists public.move_tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  phase text not null,
  due date,
  done smallint not null default 0,
  notes text not null default ''
);

create table if not exists public.move_budget (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  estimated double precision not null default 0,
  actual double precision not null default 0,
  paid smallint not null default 0,
  due date
);
alter table public.move_budget add column if not exists due date;

create table if not exists public.move_items (
  id bigint generated by default as identity primary key,
  name text not null,
  room text not null,
  qty integer not null default 1,
  cost double precision not null default 0,
  bought smallint not null default 0,
  priority text not null default 'normal'
);

create table if not exists public.move_furniture (
  id bigint generated by default as identity primary key,
  name text not null,
  room text not null,
  url text not null default '',
  image_path text not null default '',
  qty integer not null default 1,
  price double precision not null default 0,
  price_low double precision,
  price_high double precision,
  store text not null default '',
  notes text not null default '',
  ai_summary text not null default '',
  offers jsonb not null default '[]'::jsonb,
  bought smallint not null default 0,
  created_at timestamptz not null default now()
);

-- True when the signed-in user's email is on the allow list.
create or replace function public.move_is_allowed()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.move_allowed_users
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

revoke all on function public.move_is_allowed() from public, anon;
grant execute on function public.move_is_allowed() to authenticated;

alter table public.move_allowed_users enable row level security;
alter table public.move_settings enable row level security;
alter table public.move_tasks enable row level security;
alter table public.move_budget enable row level security;
alter table public.move_items enable row level security;
alter table public.move_furniture enable row level security;

revoke all on public.move_allowed_users, public.move_settings, public.move_tasks, public.move_budget, public.move_items, public.move_furniture from anon;

drop policy if exists "household only" on public.move_settings;
create policy "household only" on public.move_settings for all to authenticated
  using (public.move_is_allowed()) with check (public.move_is_allowed());
drop policy if exists "household only" on public.move_tasks;
create policy "household only" on public.move_tasks for all to authenticated
  using (public.move_is_allowed()) with check (public.move_is_allowed());
drop policy if exists "household only" on public.move_budget;
create policy "household only" on public.move_budget for all to authenticated
  using (public.move_is_allowed()) with check (public.move_is_allowed());
drop policy if exists "household only" on public.move_items;
create policy "household only" on public.move_items for all to authenticated
  using (public.move_is_allowed()) with check (public.move_is_allowed());
drop policy if exists "household only" on public.move_furniture;
create policy "household only" on public.move_furniture for all to authenticated
  using (public.move_is_allowed()) with check (public.move_is_allowed());

-- Private bucket for furniture photos (household only).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('move-furniture', 'move-furniture', false, 10485760, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

drop policy if exists "move furniture photos" on storage.objects;
create policy "move furniture photos" on storage.objects for all to authenticated
  using (bucket_id = 'move-furniture' and public.move_is_allowed())
  with check (bucket_id = 'move-furniture' and public.move_is_allowed());

